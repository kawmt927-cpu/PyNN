/** 去掉 市/县/区/自治州 等尾缀，便于匹配中心点表 */
export function normalizePlaceName(raw: string | null | undefined): string | null {
  if (!raw) return null;
  const s = raw
    .trim()
    .replace(/\s+/g, "")
    .replace(/(特别行政区|壮族自治区|回族自治区|维吾尔自治区|自治区|地区|盟)$/u, "")
    .replace(/(自治州|自治县|自治旗)$/u, "")
    .replace(/(市|县|区|旗)$/u, "");
  return s || null;
}

export function centroidForCity(city: string | null | undefined): { lng: number; lat: number } | null {
  const key = normalizePlaceName(city);
  if (!key) return null;
  return CITY_CENTROIDS[key] ?? null;
}
